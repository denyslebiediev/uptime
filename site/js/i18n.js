/** A stored 'uk'/'en' wins; else uk if any browser language is Ukrainian; else en.
 * @param {string | null} stored
 * @param {readonly string[]} languages
 * @returns {Lang}
 */
export function pickLang(stored, languages) {
  if (stored === 'uk' || stored === 'en') return stored
  return languages.some(l => l.split('-')[0].toLowerCase() === 'uk') ? 'uk' : 'en'
}

/** Looks up a string and fills {name} placeholders; an unknown key returns the key itself.
 * @param {Lang} lang
 * @param {string} key
 * @param {Record<string, string | number>} [vars]
 */
export function t(lang, key, vars = {}) {
  return (STRINGS[lang][key] ?? key).replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m))
}
